#!/usr/bin/env python3
"""Derive the modular moons viewer (index.html, src/css, src/js, src/workers, public/data) from the single-file template.

Usage: python3 tools/split_single_file.py <moons_template.html> <moons_pack_assembled.json> <bodies.json> <three_dir>

The single-file template is still the edited source in this stage. The split is mechanical: the template's one script is cut into
top-level statements, statements are assigned to modules by the names they declare, and import/export lines are added.
Nothing is rewritten by hand, so the module build and the single-file build run the same statements.
"""
import sys, re, os, json, shutil
tpl, pack, bodies, three = sys.argv[1:5]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
H = open(tpl, encoding='utf-8').read()
css = H[H.index('<style>') + 7:H.index('</style>')]
body = H[H.index('<body>') + 6:H.index('<script type="application/json" id="pack">')]
i = H.rindex('<script>') + 8; j = H.rindex('</script>'); js = H[i:j]
# strip the IIFE wrapper
a = js.index("(function(){"); b = js.rindex("})();"); inner = js[a + len("(function(){"):b]
lines = inner.split('\n')
# top-level chunks: a chunk starts at a line whose first character is not whitespace and not '}' / ')' (continuations)
chunks = []; cur = []
for ln in lines:
    start = bool(ln) and not ln[0].isspace() and ln[0] not in '})'
    if start and cur: chunks.append('\n'.join(cur)); cur = []
    cur.append(ln)
if cur: chunks.append('\n'.join(cur))
def names(ch):
    m = re.match(r'\s*(?:async\s+)?function\s+([A-Za-z_$][\w$]*)', ch)
    if m: return [m.group(1)]
    m = re.match(r'\s*([A-Za-z_$][\w$]*)\.prototype\.', ch)
    if m: return ['@proto:' + m.group(1)]
    m = re.match(r'\s*(?:const|let|var)\s+(.*)', ch, re.S)
    if m:
        # names declared at depth 0 of the declaration list
        s = m.group(1); out = []; depth = 0; tok = ''; expect = True; k = 0; quote = None
        while k < len(s):
            c = s[k]
            if quote:
                if c == '\\': k += 1
                elif c == quote: quote = None
            elif c in '\'"`': quote = c
            elif c in '([{': depth += 1
            elif c in ')]}': depth -= 1
            elif depth == 0 and c == ';': break
            elif depth == 0 and expect:
                mm = re.match(r'\s*([A-Za-z_$][\w$]*)\s*(=(?!=|>)|,|;|$)', s[k:])
                if mm: out.append(mm.group(1)); expect = False; k += mm.end(1) - 1
            elif depth == 0 and c == ',': expect = True
            k += 1
        return out
    return []
TEX = set('hash vnoise fbm sfbm q normalData CRC craters craterField JB wrapd jupBand JO jupColor latE wlonE ss cratersPL rowCand craterHi hiRow bodyHi texData'.split())
CRAFT = set('Vox @proto:Vox SM @proto:SM M2KM craftMat ORB_ZTOP ORB_ZBOT PROBE_D PROBE_H CHUTE_D CHUTE_TRAIL CHUTE_GORES CHUTE_RIBBONS HGA_HUB_Z HGA_HUB_R HGA_RIB HGA_STUCK hgaRib buildOrbiter buildOrbiterHi probeProf C_CARBON C_AFT C_RING C_DM buildProbeEntry buildProbeDescent chuteProf CHUTE_CONF buildChute buildChuteLines buildAftCover buildAeroshell'.split())
mods = {'tex': [], 'craft': [], 'main': []}; exp = {'tex': [], 'craft': []}; pending = []
for ch in chunks:
    st = ch.strip()
    if not st: continue
    if st.startswith('/*') and st.endswith('*/') and '\n' not in st.replace('\n   ', ' ').strip() or (st.startswith('/*') and re.fullmatch(r'/\*.*?\*/', st, re.S)):
        pending.append(ch); continue                      # a comment-only chunk travels with the next statement
    ns = names(ch); tgt = 'main'
    if ns and all(n in TEX for n in ns): tgt = 'tex'
    elif ns and all(n in CRAFT for n in ns): tgt = 'craft'
    elif ns and (any(n in TEX for n in ns) or any(n in CRAFT for n in ns)): raise SystemExit('mixed declaration: ' + ch[:120])
    if ns == ['JF'] and re.match(r'\s*let JF=null;', ch): tgt = 'tex'
    mods[tgt] += pending + [ch]; pending = []
    if tgt in exp: exp[tgt] += [n for n in ns if not n.startswith('@')]
mods['main'] += pending
tex = '\n'.join(mods['tex']); craft = '\n'.join(mods['craft']); main = '\n'.join(mods['main'])
# ---- textures.js (pure; runs on the main thread and in the worker)
tex_src = ("/* Procedural texture data (pure functions, no DOM): shared by the main thread and src/workers/texture-worker.js.\n   Generated from the single-file template by tools/split_single_file.py. */\n"
           "import {TAU,RAD,clamp} from './util.js';\n" + tex +
           "\nexport function setJF(v){JF=v}\nexport {" + ','.join(sorted(set(exp['tex']) - {'latE', 'wlonE', 'JO', 'CRC', 'JF'})) + "};\n")
# ---- craft.js
craft = re.sub(r'\bTIER\b', 'cfg.TIER', craft); craft = re.sub(r'\bSMK\b', 'cfg.SMK', craft)
craft_src = ("/* Spacecraft and probe models (voxel builder for LOW, mesh builder for MEDIUM/HIGH). Generated by tools/split_single_file.py. */\n"
             "import * as THREE from 'three';\nimport {TAU,RAD} from './util.js';\n/* tier settings pushed in by main.js (applyTier) */\nexport const cfg={TIER:'LOW',SMK:1};\n" + craft +
             "\nexport {" + ','.join(sorted(set(exp['craft']))) + "};\n")
# ---- main.js
def rep(s, a, b, n=1):
    assert s.count(a) == n, ('split: expected %d of %r, found %d' % (n, a[:70], s.count(a))); return s.replace(a, b)
main = rep(main, "const P=JSON.parse($('#pack').textContent);", "/* P: the data pack with data/bodies.json merged in (src/js/data.js) */")
main = rep(main, "JF=jupFeatures(SCN.tms,PROBE_WLON);", "JF=jupFeatures(SCN.tms,PROBE_WLON);setJF(JF);", 2)
main = rep(main, "HI_W=TIER==='MEDIUM'?1024:2048;SMK=TIER==='MEDIUM'?.5:1;", "HI_W=TIER==='MEDIUM'?1024:2048;SMK=TIER==='MEDIUM'?.5:1;cfg.TIER=TIER;cfg.SMK=SMK;")
a = main.index("  try{const src='\"use strict\";"); b = main.index("const nw=clamp(", a)
main = main[:a] + "  try{const url=new URL('../workers/texture-worker.js',import.meta.url);   /* module worker: imports src/js/textures.js */\n    " + main[b:]
main = rep(main, "const w=new Worker(url);", "const w=new Worker(url,{type:'module'});")
main = rep(main, "if(!R_)return;", "if(!R_)return;")
main_src = ("/* Moons and craft viewer: scene, HUD, UI. Generated from the single-file template by tools/split_single_file.py (stage 1 of the module migration:\n"
            "   textures, craft models, data loading and the worker are separate modules; the scene/HUD/UI code is still one module). */\n"
            "import * as THREE_NS from 'three';\nimport {OrbitControls} from '../vendor/OrbitControls.js';\n"
            "import {" + ','.join(sorted(set(exp['tex']) - {'latE', 'wlonE', 'JO', 'CRC', 'JF'})) + ",setJF} from './textures.js';\n"
            "import {cfg," + ','.join(sorted(set(exp['craft']))) + "} from './craft.js';\nimport {loadPack} from './data.js';\n"
            "const THREE=Object.assign({},THREE_NS,{OrbitControls});window.THREE=THREE;\nlet JF=null;\n"
            "export async function start(){\nconst P=await loadPack();\n" + main + "\n}\nstart().catch(e=>{const g=document.getElementById('gate');if(g){g.style.display='flex';g.textContent='The viewer could not start: '+e.message}console.error(e)});\n")
util_src = "/* shared constants and small helpers */\nexport const TAU=Math.PI*2, RAD=Math.PI/180;\nexport const clamp=(x,a,b)=>Math.min(b,Math.max(a,x));\n"
data_src = ("/* Data loading: the pack and the single source of truth for body radii are separate files fetched at run time. */\n"
            "const DATA=new URL('../../public/data/',import.meta.url);\n"
            "export async function loadJSON(name){const r=await fetch(new URL(name,DATA));if(!r.ok)throw new Error(name+': HTTP '+r.status);return r.json()}\n"
            "export async function loadPack(){const [P,bodies]=await Promise.all([loadJSON('moons_pack.json'),loadJSON('bodies.json')]);P.bodies=bodies;return P}\n")
worker_src = ("/* Texture worker (module worker). Builds one texture per message and returns the pixel buffers. */\n"
              "import {texData,normalData} from '../js/textures.js';\n"
              "onmessage=function(e){const sp=e.data,r=texData(sp),n=sp.ns?normalData(r.hgt,r.W,r.H,sp.ns):new Uint8ClampedArray(4);postMessage({key:sp.key,W:r.W,H:r.H,rgba:r.rgba,nrm:n},[r.rgba.buffer,n.buffer])};\n")
index = ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n'
         '<title>Galileo moons and craft</title>\n<link rel="stylesheet" href="src/css/moons.css">\n'
         '<script type="importmap">{"imports":{"three":"./src/vendor/three.module.js"}}</script>\n</head>\n<body>' + body.rstrip() + '\n<script type="module" src="src/js/main.js"></script>\n</body>\n</html>\n')
W = lambda p, s: (os.makedirs(os.path.dirname(os.path.join(ROOT, p)), exist_ok=True), open(os.path.join(ROOT, p), 'w', encoding='utf-8').write(s))
W('index.html', index); W('src/css/moons.css', css.strip() + '\n'); W('src/js/util.js', util_src); W('src/js/textures.js', tex_src); W('src/js/craft.js', craft_src)
W('src/js/data.js', data_src); W('src/js/main.js', main_src); W('src/workers/texture-worker.js', worker_src)
P = json.load(open(pack)); P.pop('bodies', None)
W('public/data/moons_pack.json', json.dumps(P, separators=(',', ':'))); shutil.copy(bodies, os.path.join(ROOT, 'public/data/bodies.json'))
shutil.copy(os.path.join(three, 'build/three.module.js'), os.path.join(ROOT, 'src/vendor/three.module.js'))
oc = open(os.path.join(three, 'examples/jsm/controls/OrbitControls.js')).read(); W('src/vendor/OrbitControls.js', oc)
shutil.copy(os.path.join(three, 'LICENSE'), os.path.join(ROOT, 'src/vendor/THREE_LICENSE'))
print('chunks', len(chunks), {k: len(v) for k, v in mods.items()}, 'exports', len(exp['tex']), len(exp['craft']))
